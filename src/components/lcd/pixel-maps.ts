export function deriveMood(s: { hp: number; fullness: number; sanity: number; poopCount: number; stage?: PetStage }): PetMood {
  if (s.hp <= 0 || s.stage === 'ZOMBIE_CORPSE') return 'DEAD';
  if (s.hp < 30 || s.sanity < 30) return 'SICK';
  if (s.fullness < 30) return 'HUNGRY';
  if (s.poopCount >= 3) return 'DIRTY';
  return 'HAPPY';
}

function stamp(grid: string[][], x: number, y: number, rows: SpriteMatrix, onlyEmpty = false) {
  rows.forEach((row, j) => {
    for (let i = 0; i < row.length; i++) {
      const ch = row[i];
      const cell = grid[y + j]?.[x + i];
      if (ch === '.' || cell === undefined) continue;
      if (onlyEmpty && cell !== '.') continue;
      grid[y + j][x + i] = ch;
    }
  });
}

// One stitch per resurrection (pet-engine R6.10), at most 3, placed on each body. Light stitches on dark bodies.
const STITCH = (c: string): SpriteMatrix => [`${c}.${c}.${c}`, `${c}${c}${c}${c}${c}`, `${c}.${c}.${c}`];
const SCARS: Partial<Record<PetStage, { shade: string; at: readonly (readonly [number, number])[] }>> = {
  BABY_GHOST: { shade: '0', at: [[8, 13], [17, 24], [9, 23]] },
  CODE_DEMON: { shade: '3', at: [[10, 10], [5, 17], [18, 25]] },
  NECROMANCER: { shade: '3', at: [[9, 20], [17, 23], [6, 26]] },
};

// Final 32x32 matrix for a stage/frame/mood. SLEEPING pins the closed-eye frame.
export function composeSprite(stage: PetStage, frame: 0 | 1, mood: PetMood = 'HAPPY', scars = 0): string[] {
  const f = mood === 'SLEEPING' ? 1 : frame;
  const grid = PIXEL_MAPS[stage][f].map((r) => r.split(''));
  const scar = SCARS[stage];
  if (scar) {
    // Frame 1 of every sprite sits one row lower, so the stitches move with the body.
    for (const [x, y] of scar.at.slice(0, Math.min(3, Math.max(0, Math.floor(scars))))) stamp(grid, x, y + f, STITCH(scar.shade));
  }
  if (stage !== 'ZOMBIE_CORPSE') {
    if (mood === 'SICK') stamp(grid, 2, 3, SWEAT);
    if (mood === 'SLEEPING') stamp(grid, 24, 1, ZZZ);
    if (mood === 'HUNGRY') {
      const m = OPEN_MOUTH[stage];
      if (m) stamp(grid, m.x, m.y + (f ? 1 : 0), m.rows);
    }
  }
  if (mood === 'PARTY') {
    const dy = frame ? 1 : 0;
    for (const [x, y, shade] of CONFETTI) stamp(grid, x + (frame ? 1 : 0), y + dy, [String(shade)], true);
  }
  return grid.map((r) => r.join(''));
}

export interface PixelRun {
  x: number;
  y: number;
  w: number;
  shade: 0 | 1 | 2 | 3;
}

// Horizontal same-shade runs; keeps the DOM small while staying pixel-exact.
export function spriteRuns(rows: SpriteMatrix): PixelRun[] {
  const runs: PixelRun[] = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      if (ch === '.') {
        x++;
        continue;
      }
      let w = 1;
      while (row[x + w] === ch) w++;
      runs.push({ x, y, w, shade: Number(ch) as PixelRun['shade'] });
      x += w;
    }
  });
  return runs;
}

// Standalone SVG string (badge card / OG image). Palette defaults to the LCD greens.
export function spriteToSvg(
  rows: SpriteMatrix,
  opts: { palette?: readonly string[]; background?: boolean; scale?: number } = {},
): string {
  const palette = opts.palette ?? LCD_PALETTE;
  const size = rows.length;
  const px = size * (opts.scale ?? 1);
  const bg = opts.background ? `<rect width="${size}" height="${size}" fill="${palette[3]}"/>` : '';
  const body = spriteRuns(rows)
    .map((r) => `<rect x="${r.x}" y="${r.y}" width="${r.w}" height="1" fill="${palette[r.shade]}"/>`)
    .join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" width="${px}" height="${px}" shape-rendering="crispEdges">${bg}${body}</svg>`;
}
